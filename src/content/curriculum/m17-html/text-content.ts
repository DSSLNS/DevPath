/** Builds a complete, valid HTML document for the web runtime. */
const page = (title: string, body: string[], css: string[] = []): string =>
  [
    "<!doctype html>",
    '<html lang="en">',
    "<head>",
    '  <meta charset="utf-8">',
    `  <title>${title}</title>`,
    "  <style>",
    "    body { font-family: system-ui, sans-serif; max-width: 680px; margin: 24px auto; padding: 0 16px; line-height: 1.6; }",
    ...css.map((line) => `    ${line}`),
    "  </style>",
    "</head>",
    "<body>",
    ...body.map((line) => `  ${line}`),
    "</body>",
    "</html>",
  ].join("\n");

